# ---------------------------------------------------------------- main

def main() -> None:
    p = argparse.ArgumentParser(prog="genome", description=__doc__.splitlines()[0])
    p.add_argument("--version", action="version", version=f"genome {VERSION}")
    sub = p.add_subparsers(dest="cmd", required=True)

    def add(name, fn, help_, *aliases):
        s = sub.add_parser(name, help=help_, aliases=list(aliases))
        s.set_defaults(fn=fn, json=False)
        if name in JSON_CMDS:
            s.add_argument("--json", action="store_true", help="machine-readable output (one JSON document)")
        return s

    s = add("init", cmd_init, "scaffold the genome (never overwrites)")
    s.add_argument("--profile", choices=PROFILES)
    s.add_argument("--modules", help="comma list, e.g. records,research")
    s.add_argument("--blueprint", action="append", metavar="NAME|FILE", help="apply a blueprint (kinds, views, playbook, routes, seed); repeatable or comma list; works on an existing genome")
    s.add_argument("--force", action="store_true")
    add("modules", cmd_modules, "show which modules are on")
    s = add("lint", cmd_lint, "check every enabled module (exit 2 on error)")
    s.add_argument("--advisory", action="store_true")
    s.add_argument("--only", choices=MODULES)
    s.add_argument("--code", nargs="+", help="only these codes, e.g. E303 W007")
    s.add_argument("--all", action="store_true", help="print every finding (default: 5 per code)")
    add("doctor", cmd_doctor, "staleness, append-only violations, unapplied rulings, running-job edits")
    add("emit", cmd_emit, "regenerate every genome zone (records, ID map, worklog index, outline); close does this too")
    add("outline", cmd_outline, "emit the stack outline zone (derived facts; the prose is docs/OUTLINE.md)")
    add("outline-check", cmd_outline_check, "exit 2 when the stack outline zone is stale (a gate)")
    s = add("wake", cmd_wake, "one-call orientation: state, resume, asks, jobs, inbox, health")
    s.add_argument("--write", action="store_true", help="regenerate the handoff zone (was `handoff --write`)")
    s = add("ask", cmd_ask, "question → the owning sections (path:lines)")
    s.add_argument("question", nargs="+")
    s.add_argument("--k", type=int, default=6)
    s.add_argument("--all", action="store_true", help="search the cards of every federated repo (repo:<name>#<class> pointers)")
    s.add_argument("--index", action="store_true", help="rank with BM25 from .genome/index.db (also searches entities)")
    s.add_argument("--show", type=int, nargs="?", const=60, default=0, help="print the best section (N lines)")
    s = add("new", cmd_new, "create an entity of a declared kind")
    s.add_argument("kind", nargs="?"); s.add_argument("--title"); s.add_argument("--set", action="append", metavar="FIELD=VALUE")
    s.add_argument("--link", action="append", metavar="REL=ID", help="an edge set at creation (repeatable; REL=A,B for several)")
    s.add_argument("--batch", metavar="FILE|-", help='JSON lines, e.g. {"kind":"claim","title":"t","set":{"quote":"q"},"link":{"cites":"@2","subject":"CO-1,CO-2"}}; @N = line N of the input (forward or back); all or nothing')
    s.add_argument("--body"); s.add_argument("--agent")
    s = add("move", cmd_move, "move an entity to a state (transitions, evidence and human-only enforced)")
    s.add_argument("id", help="an id, or several comma-separated (all checked before any moves)")
    s.add_argument("state"); s.add_argument("--evidence", help="existing path | entity id | commit:<sha> | URL"); s.add_argument("--agent")
    s.add_argument("--human", metavar="NAME", help="sign-off by a person (required for human-only states)")
    s = add("set", cmd_set, "update an entity's fields: set <id> --set field=value (types enforced)")
    s.add_argument("id"); s.add_argument("--set", action="append", metavar="FIELD=VALUE"); s.add_argument("--agent")
    s = add("link", cmd_link, "add a typed relation: link <a> <relation> <b>")
    s.add_argument("a"); s.add_argument("rel"); s.add_argument("b")
    s = add("unlink", lambda a: cmd_link(a, True), "remove a typed relation")
    s.add_argument("a"); s.add_argument("rel"); s.add_argument("b")
    s = add("show", cmd_show, "entities: fields, relations both ways, recent history (show A,B,C reads several in one call)")
    s.add_argument("id")
    s = add("find", cmd_find, "entities of a kind: find <kind> [--state S] [--where 'field op value']")
    s.add_argument("kind"); s.add_argument("--state"); s.add_argument("--where", action="append")
    s.add_argument("--limit", type=int, default=50)
    s = add("view", cmd_view, "print a saved view ([views.<name>] in genome.toml)")
    s.add_argument("name")
    s = add("impact", cmd_impact, "preview what moving <id> to a state would flag (E510), hop by hop, with the commands that follow")
    s.add_argument("id"); s.add_argument("--to", help="the state it would enter (default: the one state its pointers treat as taint)")
    s = add("graph", cmd_graph, "typed-edge queries: neighbors | path | hubs | cycles | bridges | gaps")
    s.add_argument("query"); s.add_argument("a", nargs="?"); s.add_argument("b", nargs="?")
    s.add_argument("--depth", type=int, default=2); s.add_argument("--top", type=int, default=10)
    s.add_argument("--kind", help="project onto one kind: K nodes linked directly or through one non-K node")
    s.add_argument("--across", metavar="REL|FIELD", help="namespace nodes by a relation's target or a field; keep only what crosses namespaces")
    s = add("blueprint", cmd_blueprint, "blueprints: list | show NAME | new NAME [--from BASE] | check [NAME|FILE]")
    s.add_argument("bp_cmd", choices=["list", "show", "new", "check"]); s.add_argument("name", nargs="?")
    s.add_argument("--from", dest="base", metavar="BASE", help="new: extend this blueprint")
    s.add_argument("--toml", action="store_true", help="show: the raw file"); s.add_argument("--playbook", action="store_true", help="show: the loop only")
    s.add_argument("--keep", action="store_true", help="check: keep the scratch genome")
    s = add("place", cmd_place, "where does this text land: candidate kinds, nearest entities, proposed edges")
    s.add_argument("text", nargs="+"); s.add_argument("--k", type=int, default=8)
    s = add("index", cmd_index, "build or refresh the search/graph cache (.genome/index.db)")
    s.add_argument("--rebuild", action="store_true")
    s = add("card", cmd_card, "write this repo's card (a small summary) to the cards cache")
    s.add_argument("--stdout", action="store_true"); s.add_argument("--out")
    add("federate", cmd_federate, "meta root: build every member repo's card into the cache (reads trees, writes none)")
    s = add("resolve", cmd_resolve, "repo:<name>#<class> → the file in that repo")
    s.add_argument("pointer")
    s.add_argument("--root", help="which member, when several share the name `repo:<name>`")
    s = add("verify", cmd_verify, "record that a manual was reviewed against the code it covers (sets `verified`)")
    s.add_argument("doc"); s.add_argument("--reviewed", action="store_true"); s.add_argument("--sha"); s.add_argument("--covers")
    s = add("upgrade", cmd_upgrade, "compare this repo's CLI with the skill's copy; --apply swaps it in")
    s.add_argument("--apply", action="store_true"); s.add_argument("--accept-patch-loss", action="store_true")
    add("migrate", cmd_migrate, "bring genome.toml to this CLI's schema_version")
    s = add("close", cmd_close, "iteration close: emit, lint, secrets, gate, named paths")
    s.add_argument("--no-gate", action="store_true")
    s = add("handoff", cmd_handoff, "alias of `wake --write`: the state snapshot from git + register + worklog")
    s.add_argument("--write", action="store_true")
    s = add("status", cmd_status, "supervised register transition")
    s.add_argument("id"); s.add_argument("status")
    s.add_argument("--evidence"); s.add_argument("--note"); s.add_argument("--agent")
    s = add("plan", lambda a: cmd_plan(a, "plans"), "mint a dated plan")
    s.add_argument("title")
    s = add("audit", lambda a: cmd_plan(a, "audits"), "mint a dated audit")
    s.add_argument("title")
    s = add("archive", cmd_archive, "archive a doc (or one --section of it) with a reason")
    s.add_argument("path"); s.add_argument("--reason", required=True)
    s.add_argument("--section"); s.add_argument("--generation"); s.add_argument("--by")
    s = add("log", cmd_log, "worklog: append an entry (file form) or create the next numbered file")
    s.add_argument("entry"); s.add_argument("--body"); s.add_argument("--agent")
    s.add_argument("--body-file", help="the entry body from a markdown file (`-` = stdin)")
    s = add("q", cmd_q, "operator questions: add | rule | apply | withdraw | list")
    s.add_argument("q_cmd", choices=["add", "rule", "apply", "withdraw", "list"])
    s.add_argument("id", nargs="?"); s.add_argument("text", nargs="*")
    s.add_argument("--applied", nargs="+"); s.add_argument("--open", action="store_true")

    s = add("rec", cmd_rec, "records: recon | new | amend | supersede | merge | retire | list | show | emit")
    rs = s.add_subparsers(dest="rec_cmd", required=True)
    r = rs.add_parser("recon"); r.add_argument("keywords", nargs="+")
    r = rs.add_parser("new"); r.add_argument("kind", choices=["ad", "rg", "AD", "RG"]); r.add_argument("title")
    r.add_argument("--recon", required=True); r.add_argument("--orthogonal", required=True)
    r.add_argument("--description"); r.add_argument("--severity", default="High")
    r = rs.add_parser("amend"); r.add_argument("id"); r.add_argument("--title", required=True)
    r.add_argument("--reason", required=True); r.add_argument("--body"); r.add_argument("--body-file")
    r.add_argument("--set", nargs="+", metavar="FIELD=VALUE")
    r = rs.add_parser("supersede"); r.add_argument("ids", nargs=1); r.add_argument("--by", required=True)
    r.add_argument("--reason", required=True)
    r = rs.add_parser("merge"); r.add_argument("ids", nargs="+"); r.add_argument("--into", dest="by", required=True)
    r.add_argument("--reason", required=True)
    r = rs.add_parser("retire"); r.add_argument("ids", nargs="+"); r.add_argument("--reason", required=True)
    r = rs.add_parser("list"); r.add_argument("--all", action="store_true"); r.add_argument("--json", action="store_true")
    r = rs.add_parser("show"); r.add_argument("id"); r.add_argument("--lines", type=int, default=40)
    rs.add_parser("emit")
    # legacy kb aliases: `ad "<title>"` / `rg "<title>"` → recon-free mint is gone; point at the gate
    for kind in ("ad", "rg"):
        s = add(kind, lambda a, k=kind: die(f"`{k}` is now `genome rec recon <kw>` then `genome rec new {k} ...`"),
                f"(moved) use `rec new {kind}`")
        s.add_argument("title", nargs="*")

    s = add("figure", cmd_figure, "every live occurrence of a figure (propagation check)")
    s.add_argument("value")
    s = add("quarantine", cmd_quarantine, "register invalidated figures and list where to strike them")
    s.add_argument("figures", nargs="+"); s.add_argument("--why", required=True)
    s.add_argument("--where"); s.add_argument("--by")
    s = add("hyp", cmd_hyp, "hypotheses: add | verdict | list")
    s.add_argument("hyp_cmd", choices=["add", "verdict", "list"])
    s.add_argument("id", nargs="?"); s.add_argument("text", nargs="*")
    s.add_argument("--status"); s.add_argument("--evidence"); s.add_argument("--reopen")
    s.add_argument("--note"); s.add_argument("--open", action="store_true")
    s = add("prereg", cmd_prereg, "pre-registrations: freeze <spec> | check")
    s.add_argument("pr_cmd", choices=["freeze", "check"]); s.add_argument("spec", nargs="?")
    s.add_argument("--reason"); s.add_argument("--note")
    s.add_argument("--at", help="freeze the spec as committed at this ref (backfilling a pre-registration)")
    add("secrets", cmd_secrets, "scan staged+unstaged diffs for configured secret values")

    s = add("installs", cmd_installs, "the machine's genome installs: list | verify | register | scan")
    s.add_argument("installs_cmd", choices=["list", "verify", "register", "scan"])
    s.add_argument("kind", nargs="?", help="register: skill | bin | vendored | kb")
    s.add_argument("path", nargs="?", help="register: the install path (absolute or ~)")
    s.add_argument("--note")
    s.add_argument("--against-shipped", action="store_true", dest="against_shipped",
                   help="verify: compare every install against the freshest skill/bin copy, not against its own registration")
    s.add_argument("--roots", nargs="*", default=None,
                   help="scan: directories to sweep for activated genomes (genome.toml / kb.toml) the manifest does not know")

    s = add("kb", cmd_kb, "the machine's knowledge bases: list | show | lint (reachable from anywhere)")
    s.add_argument("kb_cmd", choices=["list", "show", "lint"])
    s.add_argument("target", nargs="?", help="show/lint: a KB name or path (omit for the cwd's KB)")
    s.add_argument("--all", action="store_true", help="lint: every registered KB")

    s = add("wf", cmd_wf, "workflow boards: new | add | list")
    s.add_argument("wf_cmd", choices=["new", "add", "list"]); s.add_argument("name", nargs="?")
    s.add_argument("item", nargs="?")
    s = add("claim", cmd_claim, "claim a board item")
    s.add_argument("item"); s.add_argument("--agent")
    s = add("done", cmd_done, "move a board item")
    s.add_argument("item"); s.add_argument("new_status", choices=STATUS_VOCAB)
    s.add_argument("--evidence"); s.add_argument("--note"); s.add_argument("--agent")
    s = add("claim-register", cmd_claim_register, "claim a register row")
    s.add_argument("id"); s.add_argument("--agent")
    s = add("post", cmd_post, "post to the agent feed")
    s.add_argument("message"); s.add_argument("--wf", dest="workflow"); s.add_argument("--to")
    s.add_argument("--reply"); s.add_argument("--agent")
    s = add("feed", cmd_feed, "read the feed (your mentions)")
    s.add_argument("--wf", dest="workflow"); s.add_argument("--to"); s.add_argument("--since")

    apply_overrides(Path.cwd().resolve())
    args = p.parse_args()
    if args.cmd == "hyp" and args.hyp_cmd == "verdict":
        args.status = args.status or (args.text[0] if args.text else None)
    args.fn(args)


if __name__ == "__main__":
    main()
